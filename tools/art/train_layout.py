#!/usr/bin/env python3
"""Calibrate native frame crops without modifying the generated artwork."""
import argparse
import json
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parents[2]
OUTPUT=ROOT/'prototypes/train-sprite-layout.lua'


def inspect(kind):
    source=f'graphics/entity/train/{kind}-directions-v3.png'
    with Image.open(ROOT/source) as artwork:
        assert artwork.mode=='RGBA' and artwork.width==artwork.height,source
        alpha=artwork.getchannel('A')
        assert alpha.getextrema()==(0,255),source
        assert artwork.size==(4608,4608),source
        size=artwork.width//8
        frames=[{'x':frame%8*size,'y':frame//8*size} for frame in range(64)]
        for frame in frames:
            assert alpha.crop((frame['x'],frame['y'],frame['x']+size,frame['y']+size)).getbbox(),(kind,frame)
        return {'source':source,'atlas_size':artwork.width,'cell_size':size,'line_length':8,'width':size,'height':size,
                'scale':0.5,'shift':[0,0],'frames':frames}


def layout():
    return {kind:inspect(kind) for kind in ('locomotive','wagon')}


def lua(value):
    if isinstance(value,dict):return '{'+','.join(f'[{json.dumps(k)}]={lua(v)}' for k,v in value.items())+'}'
    if isinstance(value,list):return '{'+','.join(lua(v) for v in value)+'}'
    return json.dumps(value)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    data=layout()
    content='-- Generated by tools/art/train_layout.py; artwork pixels are unchanged.\nreturn '+lua(data)+'\n'
    if args.check:assert OUTPUT.read_text()==content,'Stale train sprite layout'
    else:OUTPUT.write_text(content)
    print(json.dumps(data,indent=2))
