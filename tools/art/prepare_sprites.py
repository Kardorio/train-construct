#!/usr/bin/env python3
"""Inspect immutable PNGs and generate Lua metadata; no image writes or rendering."""
import argparse
import hashlib
import json
import math
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "prototypes/depot-sprite-layout.lua"
PREVIEW = ROOT / ".tools/art-output/depot-sprite-layout.json"
# Explicit measurements of the approved artwork, independent of image centre.
# size, solid longitudinal endpoints, track origin, exact snapped child offset.
CALIBRATION = {
    "north": ((992, 1586), (112, 1512), (390, 812), (6.5, .5)),
    "east": ((1586, 992), (55, 1532), (793.5, 430), (.5, 6.5)),
    "south": ((992, 1586), (117, 1434), (581, 775.5), (-5.5, .5)),
    "west": ((1586, 992), (95, 1491), (793, 590), (.5, -5.5)),
}


def inspect(path):
    with Image.open(path) as image:
        assert image.format == "PNG", f"Not PNG: {path}"
        assert "A" in image.getbands() or "transparency" in image.info, f"No alpha: {path}"
        alpha = image.convert("RGBA").getchannel("A")
        assert alpha.getextrema() == (0, 255), f"Expected transparent and opaque pixels: {path}"
        return {"size": list(image.size), "bounds": list(alpha.getbbox()),
                "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}


def metadata():
    result = {"depot": {}}
    for direction, (size, ends, origin, stock) in CALIBRATION.items():
        spec = inspect(ROOT / f"graphics/entity/depot/depot-{direction}.png")
        ratio = spec["size"][0] / size[0]
        assert math.isclose(ratio, spec["size"][1] / size[1], rel_tol=1e-6), (
            f"Recalibrate {direction}: aspect ratio changed from {size} to {spec['size']}")
        origin = [v * ratio for v in origin]
        ends = [round(v * ratio) for v in ends]
        ppu = (ends[1] - ends[0]) / 32
        horizontal = direction in ("east", "west")
        along = 0 if horizontal else 1
        bounds = spec["bounds"]
        bounds[along], bounds[along+2] = ends
        # Keep the complete transverse alpha extent, including roofs and curbs.
        spec.update(ppu=ppu, origin=list(origin), stock=list(stock))
        result["depot"][direction] = spec
    return result


def lua(value, depth=0):
    if isinstance(value, dict):
        pad = "  " * (depth+1)
        return ("{\n" + ",\n".join(f"{pad}[{json.dumps(k)}]={lua(v, depth+1)}"
                                      for k, v in value.items()) + "\n" + "  "*depth + "}")
    if isinstance(value, list):
        return "{" + ",".join(map(lua, value)) + "}"
    return json.dumps(value)


def content():
    data = metadata()
    return ("-- Generated by tools/art/prepare_sprites.py; source PNGs remain untouched.\n"
            "-- Track-relative coordinates; module origin shift is always {1,1}.\n"
            "return " + lua(data) + "\n")


def preview(data):
    """Source rectangles and tile-space shifts for a CSS/canvas preview (no raster output)."""
    def subtract(r, h):
        a, b, c, d = max(r[0], h[0]), max(r[1], h[1]), min(r[2], h[2]), min(r[3], h[3])
        if a >= c or b >= d:
            return [r]
        return [q for q in ([r[0],r[1],r[2],b], [r[0],d,r[2],r[3]],
                            [r[0],b,a,d], [c,b,r[2],d]) if q[0] < q[2] and q[1] < q[3]]

    result = {"schema_version": 1, "coordinate_units": "tiles", "module_origin_shift": [1,1],
              "rail_half_width": 1.5, "depot": {}, "stock": False, "integrated": True}
    for direction, spec in data["depot"].items():
        ppu, origin = spec["ppu"], spec["origin"]
        axis = 1 if direction in ("east", "west") else 0
        track = [0,0,*spec["size"]]
        track[axis], track[axis+2] = math.floor(origin[axis]-1.5*ppu), math.ceil(origin[axis]+1.5*ppu)
        layers = []
        for x1,y1,x2,y2 in subtract(spec["bounds"], track):
            layers.append({"x": x1, "y": y1, "width": x2-x1, "height": y2-y1,
                           "scale": 32/ppu, "shift": [1+((x1+x2)/2-origin[0])/ppu,
                                                        1+((y1+y2)/2-origin[1])/ppu]})
        result["depot"][direction] = dict(spec, source=f"graphics/entity/depot/depot-{direction}.png",
                                               layers=layers)
    result["floor"] = {}
    for direction in data["depot"]:
        horizontal = direction in ("east", "west")
        start = 2 if direction == "south" else 1
        width = 8 if horizontal else 4
        layers = []
        for row in range(4 if horizontal else 32-start):
            for column in range(4 if horizontal else 1):
                cropped = start if horizontal and column == 0 else 0
                layers.append({"x": cropped*512, "y": 0, "width": (width-cropped)*512, "height": 512,
                               "scale": .0625,
                               "shift": [-15+column*width+width/2+cropped/2 if horizontal else 1,
                                         -1+row+.5 if horizontal else -15+start+row+.5]})
        result["floor"][direction] = {"source": "graphics/entity/depot/platform.png",
                                        "size": [4096, 512], "layers": layers}
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check metadata without writing")
    args = parser.parse_args()
    expected = content()
    if args.check:
        assert OUTPUT.read_text() == expected, "Stale layout: run tools/art/prepare_sprites.py"
    else:
        OUTPUT.write_text(expected)
        PREVIEW.parent.mkdir(parents=True, exist_ok=True)
        PREVIEW.write_text(json.dumps(preview(metadata()), indent=2) + "\n")
    print("Sprite metadata OK; integrated stock, railway-only clipping")
