#!/usr/bin/env python3
"""Check real sprite crops against frozen v2 references and both packaged atlases."""
import ctypes
import ctypes.util
import importlib.util
import json
import hashlib
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import zipfile
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('train_layout',ROOT/'tools/art/train_layout.py')
layout=importlib.util.module_from_spec(spec)
spec.loader.exec_module(layout)


def native_frames():
    lib=ctypes.CDLL(ctypes.util.find_library('lua5.4') or 'liblua5.4.so.0')
    lib.luaL_newstate.restype=ctypes.c_void_p
    lib.luaL_openlibs.argtypes=[ctypes.c_void_p]
    lib.luaL_loadstring.argtypes=[ctypes.c_void_p,ctypes.c_char_p]
    lib.lua_pcallk.argtypes=[ctypes.c_void_p,ctypes.c_int,ctypes.c_int,ctypes.c_int,ctypes.c_ssize_t,ctypes.c_void_p]
    lib.lua_tolstring.argtypes=[ctypes.c_void_p,ctypes.c_int,ctypes.c_void_p]
    lib.lua_tolstring.restype=ctypes.c_char_p
    lib.lua_close.argtypes=[ctypes.c_void_p]
    code='''
    function table.deepcopy(value)
      if type(value)~="table" then return value end
      local copy={};for k,v in pairs(value) do copy[k]=table.deepcopy(v) end;return copy
    end
    local graphics=require("prototypes.train-graphics")
    local rows={}
    for _,kind in ipairs{"locomotive","wagon"} do
      local layers=graphics.picture(kind).rotated.layers
      assert(#layers==2 and layers[1].draw_as_shadow and not layers[2].draw_as_shadow)
      local body=layers[2]
      assert(body.direction_count==64 and #body.frames==64 and body.line_length==8)
      assert(not body.stripes and body.filename:find("__construction%-train__/graphics/entity/train/"))
      for i,f in ipairs(body.frames) do
        rows[#rows+1]=table.concat({kind,(i-1)%body.line_length*body.width+f.x,
          math.floor((i-1)/body.line_length)*body.height+f.y,f.width,f.height,string.format("%.17g",body.scale),
          body.shift[1],body.shift[2]},"|")
      end
    end
    return table.concat(rows,"\\n")
    '''
    state=lib.luaL_newstate()
    try:
        lib.luaL_openlibs(state)
        result=lib.luaL_loadstring(state,code.encode())
        if not result:result=lib.lua_pcallk(state,0,1,0,0,None)
        text=lib.lua_tolstring(state,-1,None).decode()
        assert not result,text
        return [line.split('|') for line in text.splitlines()]
    finally:lib.lua_close(state)


def main():
    import os
    os.chdir(ROOT)
    data=layout.layout()
    expected='-- Generated by tools/art/train_layout.py; artwork pixels are unchanged.\nreturn '+layout.lua(data)+'\n'
    assert layout.OUTPUT.read_text()==expected,'Stale calibrated train metadata'
    rows=native_frames()
    envelopes=json.loads((ROOT/'tools/art/train-native-envelope-64.json').read_text())
    keyframes=json.loads((ROOT/'tests/fixtures/train-keyframes-v2.json').read_text())
    assert set(keyframes['sha256_rgba'])=={'locomotive','wagon'}
    assert keyframes['crop_size']==[576,576]
    for kind,art in data.items():
        source=ROOT/art['source']
        assert source.read_bytes()[24]==8,'Train atlas must use 8-bit PNG channels'
        assert len(keyframes['sha256_rgba'][kind])==16
        with Image.open(source) as image:
            assert image.mode=='RGBA'
            alpha=image.getchannel('A')
            native=[r[1:] for r in rows if r[0]==kind]
            assert len(native)==64
            for index,(row,frame) in enumerate(zip(native,art['frames'])):
                actual=list(map(int,row[:4]));scale,sx,sy=map(float,row[4:])
                x,y,width,height=actual
                assert actual==[frame['x'],frame['y'],art['width'],art['height']]
                assert 0<=x<image.width and 0<=y<image.height and x+width<=image.width and y+height<=image.height
                mask=alpha.crop((x,y,x+width,y+height)).point(lambda a:255 if a>=128 else 0)
                box=mask.getbbox();assert box
                size=[(box[2]-box[0])*scale,(box[3]-box[1])*scale]
                center=[((box[0]+box[2]-width)/2)*scale+sx*32,((box[1]+box[3]-height)/2)*scale+sy*32]
                expected=envelopes[kind][index]
                tolerance=1 if index%4==0 else 2
                assert all(abs(a-b)<=tolerance for a,b in zip(size,expected['size'])),(kind,index,'undersized body',size,expected['size'])
                assert all(abs(a-b)<=tolerance for a,b in zip(center,expected['center'])),(kind,index,'misaligned pivot',center,expected['center'])
            hashes=set()
            for index,frame in enumerate(art['frames']):
                crop=image.crop((frame['x'],frame['y'],frame['x']+art['width'],frame['y']+art['height']))
                digest=hashlib.sha256(crop.tobytes()).hexdigest()
                hashes.add(digest)
                if index%4==0:
                    assert crop.size==tuple(keyframes['crop_size'])
                    assert digest==keyframes['sha256_rgba'][kind][index//4],(kind,index,'Validated direction was repainted')
            assert len(hashes)==64,'Repeated frames do not smooth the turn'
    with tempfile.TemporaryDirectory(prefix='ct-train-art-') as temporary:
        project=Path(temporary)
        (project/'tools').mkdir()
        shutil.copy2(ROOT/'tools/build.py',project/'tools/build.py')
        shutil.copy2(ROOT/'info.json',project/'info.json')
        shutil.copytree(ROOT/'graphics/entity/train',project/'graphics/entity/train')
        for variant in ([],['beta']):
            subprocess.run([sys.executable,str(project/'tools/build.py'),'package',*variant],check=True,capture_output=True)
            info=json.loads((ROOT/'info.json').read_text())
            name='train-construct' if variant else info['name']
            with zipfile.ZipFile(project/f"dist/{name}_{info['version']}.zip") as archive:
                atlas_members={name for name in archive.namelist() if '/graphics/entity/train/' in name}
                assert atlas_members=={f"{name}_{info['version']}/{art['source']}" for art in data.values()},'Unused train artwork was packaged'
                for art in data.values():
                    assert archive.read(f"{name}_{info['version']}/{art['source']}")==(ROOT/art['source']).read_bytes()
    print('CT_TRAIN_GRAPHICS SUCCESS: 128 native envelopes/pivots, 32 unchanged keyframes, both packaged atlases')


if __name__=='__main__':main()
